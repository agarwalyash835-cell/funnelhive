const MAPS = {};
const fill = (s, vars) => (vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s);
// t('Resend in {n}s', { n: 30 }) in the given language; anything not in its dictionary stays as passed
export function learnT(lang) {
  const list = DICTS[lang];
  if (list && !MAPS[lang]) MAPS[lang] = Object.fromEntries(KEYS.map((k, i) => [k, list[i]]).filter(([, v]) => v));
  const map = MAPS[lang] || {};
  return (s, vars) => fill(map[s] || s, vars);
}
